package io.github.yousefibehnam.jqa.summary;

import io.github.yousefibehnam.jqa.metrics.ResolutionStats;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;

/** Renders per-project metric distributions and pooled rank correlations as Markdown. */
public final class SummaryReport {

    /** One analysed project: its per-class rows and optional resolution statistics. */
    public record Project(String name, List<Map<String, String>> rows, ResolutionStats stats) {
    }

    static final List<String> METRICS = List.of("wmc", "dit", "noc", "cbo", "rfc", "lcom", "lcom_star");
    private static final Set<String> CONCRETE_KINDS = Set.of("class", "enum", "record");
    private static final int TOP = 5;

    private SummaryReport() {
    }

    public static String render(List<Project> projects, List<String> notes) {
        StringBuilder md = new StringBuilder();
        md.append("# Case-study results\n\n");
        md.append("Generated by `jqa summarize` from the per-class CSV files in this directory. ")
                .append("Distributions cover classes, enums and records; interfaces and annotation types ")
                .append("are excluded because they have no implementation to measure. LCOM* statistics only ")
                .append("include classes where it is defined (at least two methods and one field). ")
                .append("Quantiles use linear interpolation.\n\n");
        for (String note : notes) {
            md.append("- ").append(note).append('\n');
        }
        if (!notes.isEmpty()) {
            md.append('\n');
        }

        overview(md, projects);
        for (Project project : projects) {
            distribution(md, project);
        }
        largest(md, projects);
        correlations(md, projects);
        return md.toString();
    }

    private static List<Map<String, String>> concrete(Project project) {
        return project.rows().stream().filter(r -> CONCRETE_KINDS.contains(r.get("kind"))).toList();
    }

    private static void overview(StringBuilder md, List<Project> projects) {
        md.append("## Overview\n\n");
        md.append("| Project | Source files | Types | Classes, enums, records | DIT lower bounds | ")
                .append("Call sites resolved | Type references resolved |\n");
        md.append("|---|---:|---:|---:|---:|---:|---:|\n");
        for (Project p : projects) {
            List<Map<String, String>> concrete = concrete(p);
            long lowerBounds = concrete.stream().filter(r -> "false".equals(r.get("dit_exact"))).count();
            ResolutionStats s = p.stats();
            md.append(String.format(Locale.ROOT, "| %s | %s | %d | %d | %d | %s | %s |%n",
                    p.name(),
                    s == null ? "n/a" : Integer.toString(s.files()),
                    p.rows().size(), concrete.size(), lowerBounds,
                    s == null ? "n/a" : percent(s.callResolutionRate()),
                    s == null ? "n/a" : percent(s.typeResolutionRate())));
        }
        md.append("\n\"DIT lower bounds\" counts classes with a supertype outside the JDK and the analysed ")
                .append("sources, whose DIT is therefore a lower bound.\n\n");
    }

    private static void distribution(StringBuilder md, Project project) {
        List<Map<String, String>> rows = concrete(project);
        md.append("## ").append(project.name()).append("\n\n");
        md.append("| Metric | n | Mean | Median | P90 | Max |\n");
        md.append("|---|---:|---:|---:|---:|---:|\n");
        for (String metric : METRICS) {
            double[] values = values(rows, metric);
            if (values.length == 0) {
                md.append("| ").append(label(metric)).append(" | 0 | | | | |\n");
                continue;
            }
            boolean ratio = metric.equals("lcom_star");
            md.append(String.format(Locale.ROOT, "| %s | %d | %s | %s | %s | %s |%n",
                    label(metric), values.length,
                    number(Statistics.mean(values), 2),
                    number(Statistics.median(values), ratio ? 2 : 1),
                    number(Statistics.quantile(values, 0.9), ratio ? 2 : 1),
                    number(Statistics.max(values), ratio ? 2 : 0)));
        }
        md.append('\n');
    }

    private static void largest(StringBuilder md, List<Project> projects) {
        md.append("## Largest classes by WMC\n\n");
        md.append("| Project | Class | WMC | RFC | CBO | LCOM* |\n");
        md.append("|---|---|---:|---:|---:|---:|\n");
        for (Project p : projects) {
            List<Map<String, String>> rows = new ArrayList<>(concrete(p));
            rows.sort(Comparator.comparingInt((Map<String, String> r) -> Integer.parseInt(r.get("wmc"))).reversed()
                    .thenComparing(r -> r.get("class")));
            for (Map<String, String> r : rows.subList(0, Math.min(TOP, rows.size()))) {
                String lcomStar = r.get("lcom_star");
                md.append(String.format(Locale.ROOT, "| %s | `%s` | %s | %s | %s | %s |%n",
                        p.name(), r.get("class"), r.get("wmc"), r.get("rfc"), r.get("cbo"),
                        lcomStar.isEmpty() ? "n/a" : number(Double.parseDouble(lcomStar), 2)));
            }
        }
        md.append('\n');
    }

    private static void correlations(StringBuilder md, List<Project> projects) {
        List<Map<String, String>> pooled = new ArrayList<>();
        projects.forEach(p -> pooled.addAll(concrete(p)));
        md.append("## Spearman rank correlation between metrics (all projects pooled)\n\n");
        md.append("Each cell uses the classes where both metrics are defined (n = ")
                .append(pooled.size()).append(", fewer for LCOM*).\n\n");
        md.append("| |");
        METRICS.forEach(m -> md.append(' ').append(label(m)).append(" |"));
        md.append("\n|---|");
        METRICS.forEach(m -> md.append("---:|"));
        md.append('\n');
        for (String a : METRICS) {
            md.append("| ").append(label(a)).append(" |");
            for (String b : METRICS) {
                List<Map<String, String>> both = pooled.stream()
                        .filter(r -> !r.get(a).isEmpty() && !r.get(b).isEmpty()).toList();
                double rho = Statistics.spearman(values(both, a), values(both, b));
                md.append(' ').append(Double.isNaN(rho) ? "n/a" : number(rho, 2)).append(" |");
            }
            md.append('\n');
        }
        md.append('\n');
    }

    private static double[] values(List<Map<String, String>> rows, String metric) {
        return rows.stream().map(r -> r.get(metric)).filter(v -> v != null && !v.isEmpty())
                .mapToDouble(Double::parseDouble).toArray();
    }

    private static String label(String metric) {
        return metric.equals("lcom_star") ? "LCOM*" : metric.toUpperCase(Locale.ROOT);
    }

    private static String number(double value, int decimals) {
        return String.format(Locale.ROOT, "%." + decimals + "f", value);
    }

    private static String percent(double rate) {
        return String.format(Locale.ROOT, "%.1f%%", 100 * rate);
    }
}
